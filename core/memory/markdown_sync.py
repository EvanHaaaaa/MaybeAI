import time
from pathlib import Path
from typing import Dict, Any, List, Optional

class MarkdownBrainSync:
    """
    Second Brain synchronizer following the Andrej Karpathy paradigm:
    Stores and syncs all AI memories, viewer dossiers, daily journals,
    and promises into human-readable, transparent, and editable Markdown files.
    
    Directories:
    - data/second_brain/journals/YYYY-MM-DD.md (Daily stream logs)
    - data/second_brain/users/{username}.md (Viewer dossiers)
    - data/second_brain/promises.md (Active promises & challenges)
    - data/second_brain/MEMORY_INDEX.md (Master Brain Index)
    """

    def __init__(self, base_dir: str = "data/second_brain"):
        self.base_dir = Path(base_dir)
        self.journals_dir = self.base_dir / "journals"
        self.users_dir = self.base_dir / "users"
        self.journals_dir.mkdir(parents=True, exist_ok=True)
        self.users_dir.mkdir(parents=True, exist_ok=True)
        self._ensure_index_files()

    def _ensure_index_files(self):
        index_file = self.base_dir / "MEMORY_INDEX.md"
        if not index_file.exists():
            index_file.write_text("""# 🧠 Eve Maybe's Second Brain (BrainMap Index)
*Building a Second Brain the Andrej Karpathy Way: LLMs and Markdown*

Welcome to Eve Maybe's long-term episodic memory index.
Here, all stream moments, gaming incidents, viewer preferences, and promises are preserved.

## 🗂️ Structure
- `journals/`: Chronological daily episodic journals of all live stream events.
- `users/`: Persistent viewer dossiers with preferences, game history, and rapport notes.
- `promises.md`: Active, fulfilled, and pending promises made between Eve and chatters.

---
*Generated by MaybeAI Autonomous Memory Subsystem*
""", encoding="utf-8")

        promises_file = self.base_dir / "promises.md"
        if not promises_file.exists():
            promises_file.write_text("""# 🤝 Eve's Promises & Challenges Board

| ID | User | Type | Status | Created | Description |
|---|---|---|---|---|---|
""", encoding="utf-8")

    def sync_episodic_memory(self, memory: Dict[str, Any]):
        """Syncs a single episodic memory into today's Markdown journal and user dossier."""
        now = memory.get("timestamp", time.time())
        day_str = time.strftime("%Y-%m-%d", time.localtime(now))
        time_str = time.strftime("%H:%M:%S", time.localtime(now))
        journal_file = self.journals_dir / f"{day_str}.md"

        # 1. Append to daily journal
        if not journal_file.exists():
            journal_file.write_text(f"""# 📓 Daily Stream Journal: {day_str}
Eve Maybe's episodic memory logs for stream session on {day_str}.

---
""", encoding="utf-8")

        title = memory.get("title", "Episodic Moment")
        content = memory.get("content", "")
        ep_type = memory.get("episode_type", "general")
        user = memory.get("user", "Chat")
        emotion = memory.get("emotional_tag", "neutral")
        importance = memory.get("importance_score", 0.5)
        game_context = memory.get("game_context", "")

        entry_md = f"""
### [{time_str}] {title}
- **Type:** `{ep_type}` | **Participant:** **{user}**
- **Emotion:** `{emotion}` | **Importance:** `{importance}`
- **Context:** {game_context or "General Stream"}

> {content}
"""
        with open(journal_file, "a", encoding="utf-8") as f:
            f.write(entry_md)

        # 2. Update user dossier if individual viewer
        if user and user not in ("Chat", "System", "Eve", "EveMaybe"):
            self._update_user_dossier(user, title, content, day_str)

        # 3. Update master index highlights
        self._update_master_index(title, user, ep_type, day_str)

    def _update_user_dossier(self, username: str, title: str, content: str, date_str: str):
        clean_user = "".join(c for c in username if c.isalnum() or c in ("_", "-")) or "viewer"
        user_file = self.users_dir / f"{clean_user}.md"

        if not user_file.exists():
            header = f"""# 👤 Viewer Dossier: {username}
*First seen: {date_str}*

## 🌟 Memorable Episodes & Incidents
"""
            user_file.write_text(header, encoding="utf-8")

        with open(user_file, "a", encoding="utf-8") as f:
            f.write(f"- **[{date_str}] {title}:** {content}\n")

    def sync_promise(self, promise_id: int, user: str, text: str, ptype: str, status: str):
        promises_file = self.base_dir / "promises.md"
        today = time.strftime("%Y-%m-%d", time.localtime())
        row = f"| {promise_id} | {user} | {ptype} | {status} | {today} | {text} |\n"
        with open(promises_file, "a", encoding="utf-8") as f:
            f.write(row)

    def _update_master_index(self, title: str, user: str, ep_type: str, date_str: str):
        index_file = self.base_dir / "MEMORY_INDEX.md"
        if index_file.exists():
            content = index_file.read_text(encoding="utf-8")
            if "## 🌟 Latest Memorable Highlights" not in content:
                content += "\n## 🌟 Latest Memorable Highlights\n"
            content += f"- **[{date_str}]** [{ep_type}] **{user}**: {title}\n"
            # Keep only the latest 20 highlights
            lines = content.splitlines()
            if len(lines) > 60:
                header_part = "\n".join(lines[:30])
                highlights = [l for l in lines[30:] if l.startswith("- **[")]
                content = header_part + "\n" + "\n".join(highlights[-20:]) + "\n"
            index_file.write_text(content, encoding="utf-8")

    def get_latest_journal_markdown(self) -> str:
        today = time.strftime("%Y-%m-%d", time.localtime())
        journal_file = self.journals_dir / f"{today}.md"
        if journal_file.exists():
            return journal_file.read_text(encoding="utf-8")
        # Try latest available journal
        journals = sorted(list(self.journals_dir.glob("*.md")), reverse=True)
        if journals:
            return journals[0].read_text(encoding="utf-8")
        return "# No stream journals recorded yet."
