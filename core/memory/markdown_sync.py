import time
from pathlib import Path
from typing import Dict, Any, List, Optional

class MarkdownBrainSync:
    """
    Second Brain synchronizer following the Andrej Karpathy paradigm:
    Stores and syncs all AI memories, viewer dossiers, daily journals,
    and promises into human-readable, transparent, and editable Markdown files.
    
    Directories:
    - data/second_brain/journals/YYYY-MM-DD.md (Daily stream logs)
    - data/second_brain/users/{username}.md (Viewer dossiers)
    - data/second_brain/promises.md (Active promises & challenges)
    - data/second_brain/MEMORY_INDEX.md (Master Brain Index)
    """

    def __init__(self, base_dir: str = "data/second_brain"):
        self.base_dir = Path(base_dir)
        self.journals_dir = self.base_dir / "journals"
        self.users_dir = self.base_dir / "users"
        self.journals_dir.mkdir(parents=True, exist_ok=True)
        self.users_dir.mkdir(parents=True, exist_ok=True)
        self._ensure_index_files()

    def _ensure_index_files(self):
        index_file = self.base_dir / "MEMORY_INDEX.md"
        if not index_file.exists():
            index_file.write_text("""# 🧠 Eve Maybe's Second Brain (BrainMap Index)
*Building a Second Brain the Andrej Karpathy Way: LLMs and Markdown*

Welcome to Eve Maybe's long-term episodic memory index.
Here, all stream moments, gaming incidents, viewer preferences, and promises are preserved.

## 🗂️ Structure
- `journals/`: Chronological daily episodic journals of all live stream events.
- `users/`: Persistent viewer dossiers with preferences, game history, and rapport notes.
- `promises.md`: Active, fulfilled, and pending promises made between Eve and chatters.

---
*Generated by MaybeAI Autonomous Memory Subsystem*
""", encoding="utf-8")

        promises_file = self.base_dir / "promises.md"
        if not promises_file.exists():
            promises_file.write_text("""# 🤝 Eve's Promises & Challenges Board

| ID | User | Type | Status | Created | Description |
|---|---|---|---|---|---|
""", encoding="utf-8")

    def sync_episodic_memory(self, memory: Dict[str, Any]):
        """Syncs a single episodic memory into today's Markdown journal and user dossier."""
        now = memory.get("timestamp", time.time())
        day_str = time.strftime("%Y-%m-%d", time.localtime(now))
        time_str = time.strftime("%H:%M:%S", time.localtime(now))
        journal_file = self.journals_dir / f"{day_str}.md"

        # 1. Append to daily journal
        if not journal_file.exists():
            journal_file.write_text(f"""# 📓 Daily Stream Journal: {day_str}
Eve Maybe's episodic memory logs for stream session on {day_str}.

---
""", encoding="utf-8")

        title = memory.get("title", "Episodic Moment")
        content = memory.get("content", "")
        ep_type = memory.get("episode_type", "general")
        user = memory.get("user", "Chat")
        emotion = memory.get("emotional_tag", "neutral")
        importance = memory.get("importance_score", 0.5)
        game_context = memory.get("game_context", "")

        entry_md = f"""
### [{time_str}] {title}
- **Type:** `{ep_type}` | **Participant:** **{user}**
- **Emotion:** `{emotion}` | **Importance:** `{importance}`
- **Context:** {game_context or "General Stream"}

> {content}
"""
        with open(journal_file, "a", encoding="utf-8") as f:
            f.write(entry_md)

        # 2. Update user dossier if individual viewer
        if user and user not in ("Chat", "System", "Eve", "EveMaybe"):
            self._update_user_dossier(user, title, content, day_str)

        # 3. Update master index highlights
        self._update_master_index(title, user, ep_type, day_str)

    def _update_user_dossier(self, username: str, title: str, content: str, date_str: str):
        clean_user = "".join(c for c in username if c.isalnum() or c in ("_", "-")) or "viewer"
        user_file = self.users_dir / f"{clean_user}.md"

        if not user_file.exists():
            header = f"""# 👤 Viewer Dossier: {username}
*First seen: {date_str}*

## 🌟 Memorable Episodes & Incidents
"""
            user_file.write_text(header, encoding="utf-8")

        with open(user_file, "a", encoding="utf-8") as f:
            f.write(f"- **[{date_str}] {title}:** {content}\n")

    def sync_promise(
        self,
        promise_id: int,
        user: str,
        text: str,
        ptype: str,
        status: str,
        created_at: Optional[float] = None,
        max_completed_rows: int = 20,
    ):
        """Upserts a promise/challenge row in promises.md and archives overflow completed rows."""
        promises_file = self.base_dir / "promises.md"
        created_str = time.strftime(
            "%Y-%m-%d",
            time.localtime(created_at if created_at is not None else time.time()),
        )
        clean_text = " ".join(str(text).replace("|", "/").splitlines()).strip()
        clean_user = str(user).replace("|", "/").strip()
        clean_ptype = str(ptype).replace("|", "/").strip()
        clean_status = str(status).replace("|", "/").strip().lower()

        rows = self._read_promise_rows(promises_file)
        updated = False
        for row in rows:
            if row["id"] == str(promise_id):
                row["user"] = clean_user
                row["type"] = clean_ptype
                row["status"] = clean_status
                row["description"] = clean_text
                updated = True
                break
        if not updated:
            rows.append({
                "id": str(promise_id),
                "user": clean_user,
                "type": clean_ptype,
                "status": clean_status,
                "created": created_str,
                "description": clean_text,
            })

        self._write_bounded_promises(rows, max_completed_rows=max_completed_rows)

    def fulfill_promise(self, promise_id: int, max_completed_rows: int = 20) -> bool:
        """Marks an existing promise row as fulfilled in promises.md and archives overflow."""
        promises_file = self.base_dir / "promises.md"
        rows = self._read_promise_rows(promises_file)
        found = False
        for row in rows:
            if row["id"] == str(promise_id):
                row["status"] = "fulfilled"
                found = True
                break
        if found:
            self._write_bounded_promises(rows, max_completed_rows=max_completed_rows)
        return found

    def sync_promises_from_db(self, db: Any, max_completed_rows: int = 20) -> None:
        """Synchronizes promises.md and promises_archive.md from SQLite promises_challenges."""
        if not hasattr(db, "get_promises"):
            return
        db_rows = db.get_promises(limit=500)
        rows: List[Dict[str, str]] = []
        for item in db_rows:
            created_ts = item.get("created_at") or time.time()
            created_str = time.strftime("%Y-%m-%d", time.localtime(created_ts))
            clean_text = " ".join(str(item.get("text", "")).replace("|", "/").splitlines()).strip()
            rows.append({
                "id": str(item.get("id", "")),
                "user": str(item.get("user", "")).replace("|", "/").strip(),
                "type": str(item.get("type", "promise")).replace("|", "/").strip(),
                "status": str(item.get("status", "pending")).replace("|", "/").strip().lower(),
                "created": created_str,
                "description": clean_text,
            })
        self._write_bounded_promises(rows, max_completed_rows=max_completed_rows)

    def sync_promises_bidirectional(self, db: Any, max_completed_rows: int = 20) -> Dict[str, int]:
        """
        Bidirectionally reconciles promises.md with SQLite promises_challenges:
        - Markdown status updates (e.g., pending -> fulfilled) propagate into SQLite.
        - New rows added manually to promises.md (missing/non-numeric ID) are inserted into SQLite.
        - DB-side updates propagate back into bounded promises.md and promises_archive.md.
        """
        if not hasattr(db, "get_promises"):
            return {"imported_from_md": 0, "updated_in_db": 0, "synced_to_md": 0}

        promises_file = self.base_dir / "promises.md"
        md_rows = self._read_promise_rows(promises_file)
        db_rows = db.get_promises(limit=1000)
        db_by_id = {str(r.get("id")): r for r in db_rows}

        imported = 0
        updated_db = 0

        for md in md_rows:
            md_id = str(md.get("id", "")).strip()
            md_status = str(md.get("status", "pending")).strip().lower()
            md_user = str(md.get("user", "")).strip()
            md_desc = str(md.get("description", "")).strip()
            md_type = str(md.get("type", "promise")).strip() or "promise"

            if md_id.isdigit() and md_id in db_by_id:
                db_item = db_by_id[md_id]
                db_status = str(db_item.get("status", "pending")).strip().lower()
                if db_status == "pending" and md_status in ("fulfilled", "archived", "cancelled"):
                    if hasattr(db, "update_promise_status"):
                        if db.update_promise_status(int(md_id), md_status):
                            updated_db += 1
                    elif md_status == "fulfilled" and hasattr(db, "fulfill_promise"):
                        if db.fulfill_promise(int(md_id)):
                            updated_db += 1
            elif md_user and md_desc and not md_id.isdigit():
                if hasattr(db, "add_promise_or_challenge"):
                    new_pid = db.add_promise_or_challenge(
                        user=md_user,
                        text=md_desc,
                        ptype=md_type,
                        context="promises.md bidirectional sync",
                    )
                    imported += 1
                    if md_status in ("fulfilled", "archived", "cancelled"):
                        if hasattr(db, "update_promise_status"):
                            db.update_promise_status(new_pid, md_status)
                        elif md_status == "fulfilled" and hasattr(db, "fulfill_promise"):
                            db.fulfill_promise(new_pid)

        self.sync_promises_from_db(db, max_completed_rows=max_completed_rows)
        final_rows = self._read_promise_rows(promises_file)
        return {
            "imported_from_md": imported,
            "updated_in_db": updated_db,
            "synced_to_md": len(final_rows),
        }

    def _read_promise_rows(self, promises_file: Path) -> List[Dict[str, str]]:
        if not promises_file.exists():
            return []
        rows: List[Dict[str, str]] = []
        for line in promises_file.read_text(encoding="utf-8").splitlines():
            stripped = line.strip()
            if not stripped.startswith("|") or stripped.startswith("| ID |") or stripped.startswith("|---"):
                continue
            parts = [p.strip() for p in stripped.strip("|").split("|")]
            if len(parts) >= 6:
                rows.append({
                    "id": parts[0],
                    "user": parts[1],
                    "type": parts[2],
                    "status": parts[3].lower(),
                    "created": parts[4],
                    "description": " | ".join(parts[5:]),
                })
        return rows

    def _write_bounded_promises(self, rows: List[Dict[str, str]], max_completed_rows: int = 20) -> None:
        promises_file = self.base_dir / "promises.md"
        archive_file = self.base_dir / "promises_archive.md"

        active_rows = [r for r in rows if r.get("status") == "pending"]
        completed_rows = [r for r in rows if r.get("status") != "pending"]

        cap = max(0, int(max_completed_rows))
        overflow_rows: List[Dict[str, str]] = []
        if len(completed_rows) > cap:
            overflow_count = len(completed_rows) - cap
            overflow_rows = completed_rows[:overflow_count]
            completed_rows = completed_rows[overflow_count:]

        if overflow_rows:
            if not archive_file.exists():
                archive_file.write_text(
                    "# 📦 Eve's Archived Promises & Challenges\n\n"
                    "| ID | User | Type | Status | Created | Description |\n"
                    "|---|---|---|---|---|---|\n",
                    encoding="utf-8",
                )
            with open(archive_file, "a", encoding="utf-8") as af:
                for r in overflow_rows:
                    af.write(f"| {r['id']} | {r['user']} | {r['type']} | {r['status']} | {r['created']} | {r['description']} |\n")

        header = (
            "# 🤝 Eve's Promises & Challenges Board\n\n"
            "| ID | User | Type | Status | Created | Description |\n"
            "|---|---|---|---|---|---|\n"
        )
        body_lines = [
            f"| {r['id']} | {r['user']} | {r['type']} | {r['status']} | {r['created']} | {r['description']} |\n"
            for r in (active_rows + completed_rows)
        ]
        promises_file.write_text(header + "".join(body_lines), encoding="utf-8")

    def _update_master_index(self, title: str, user: str, ep_type: str, date_str: str):
        index_file = self.base_dir / "MEMORY_INDEX.md"
        if index_file.exists():
            content = index_file.read_text(encoding="utf-8")
            if "## 🌟 Latest Memorable Highlights" not in content:
                content += "\n## 🌟 Latest Memorable Highlights\n"
            content += f"- **[{date_str}]** [{ep_type}] **{user}**: {title}\n"
            # Keep only the latest 20 highlights
            lines = content.splitlines()
            if len(lines) > 60:
                header_part = "\n".join(lines[:30])
                highlights = [l for l in lines[30:] if l.startswith("- **[")]
                content = header_part + "\n" + "\n".join(highlights[-20:]) + "\n"
            index_file.write_text(content, encoding="utf-8")

    def get_latest_journal_markdown(self) -> str:
        today = time.strftime("%Y-%m-%d", time.localtime())
        journal_file = self.journals_dir / f"{today}.md"
        if journal_file.exists():
            return journal_file.read_text(encoding="utf-8")
        # Try latest available journal
        journals = sorted(list(self.journals_dir.glob("*.md")), reverse=True)
        if journals:
            return journals[0].read_text(encoding="utf-8")
        return "# No stream journals recorded yet."
